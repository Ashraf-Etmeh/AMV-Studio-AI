import { expect, test } from '@playwright/test'

test('Director and Copilot change only the illustrative storyboard', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Projects', exact: true }).click()
  await page.getByRole('button', { name: 'Open project Beneath the Sky' }).click()
  await page.getByRole('button', { name: 'AMV Planner' }).click()
  await expect(page.getByRole('heading', { name: 'AMV Planner' })).toBeVisible()
  await expect(page.getByText('Hand-authored sample plans · no imported media analyzed')).toBeVisible()
  await expect(page.getByText('Your imported files are not used in these examples.')).toBeVisible()
  const preview = page.locator('section[aria-label="Selected sample story beat"]')
  await expect(preview.getByRole('heading', { name: 'Reaching Out' })).toBeVisible()

  await page.getByRole('button', { name: /Stand and Return/ }).click()
  await expect(preview.getByRole('heading', { name: 'Final Confrontation' })).toBeVisible()
  await page.getByRole('button', { name: 'Select beat 2, Verse' }).click()
  await expect(preview.getByRole('heading', { name: 'Alone at Sunset' })).toBeVisible()
  await page.getByRole('button', { name: 'Use this sample plan' }).click()
  await expect(page.getByRole('button', { name: 'AI Copilot' })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByText('0 beats changed from the applied example')).toBeVisible()
  await page.getByRole('button', { name: 'Select beat 3, Chorus' }).click()
  await page.getByRole('button', { name: 'Use Reunion for Chorus' }).click()
  await expect(preview.getByRole('heading', { name: 'Reunion' })).toBeVisible()
  await expect(page.getByText('1 beat changed from the applied example')).toBeVisible()
  await expect(page.getByText('No model ranked your clips or analyzed your media.')).toBeVisible()
  await page.screenshot({ path: 'test-results/planner-copilot-1672x941.png', fullPage: true })
  await page.getByRole('button', { name: 'Reset draft' }).click()
  await expect(preview.getByRole('heading', { name: 'Final Confrontation' })).toBeVisible()
  await expect(page.getByText('0 beats changed from the applied example')).toBeVisible()

  await page.getByRole('button', { name: 'AI Director' }).click()
  await page.getByRole('button', { name: /From Rain to Reunion/ }).click()
  await page.getByRole('button', { name: 'Use this sample plan' }).click()
  await expect(preview.getByRole('heading', { name: 'Reaching Out' })).toBeVisible()
  await expect(page.getByText('No media or timeline was changed.')).toBeVisible()
  await page.getByRole('button', { name: 'Use Reunion for Chorus' }).click()
  await expect(preview.getByRole('heading', { name: 'Reunion' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'AI Director' })).toHaveAttribute('aria-pressed', 'true')
  await expect(preview.getByRole('heading', { name: 'Reaching Out' })).toBeVisible()

  await page.screenshot({ path: 'test-results/planner-1672x941.png', fullPage: true })
  for (const viewport of [{ width: 1280, height: 800 }, { width: 390, height: 844 }]) {
    await page.setViewportSize(viewport)
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: `test-results/planner-${viewport.width}x${viewport.height}.png`, fullPage: true })
  }
  expect(errors).toEqual([])
})

test('imported music count does not change the example plan', async ({ page }) => {
  const sampleCount = 8_000
  const wav = Buffer.alloc(44 + sampleCount * 2)
  wav.write('RIFF', 0); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVE', 8)
  wav.write('fmt ', 12); wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20)
  wav.writeUInt16LE(1, 22); wav.writeUInt32LE(8_000, 24); wav.writeUInt32LE(16_000, 28)
  wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34)
  wav.write('data', 36); wav.writeUInt32LE(sampleCount * 2, 40)
  await page.goto('/')
  await page.getByRole('button', { name: 'Projects', exact: true }).click()
  await page.getByRole('button', { name: 'New Project' }).click()
  await page.getByLabel('Project name').fill('My AMV plan')
  await page.getByRole('button', { name: 'Create Project' }).click()
  await page.getByLabel('Choose media files').setInputFiles({ name: 'my-song.wav', mimeType: 'audio/wav', buffer: wav })
  await page.getByRole('button', { name: 'AMV Planner' }).click()
  await expect(page.getByText('Your imported files are not used in these examples.')).toBeVisible()
  await expect(page.getByText('Neon Memories · 0:45 – 1:29')).toBeVisible()
  await expect(page.getByText('my-song.wav')).toHaveCount(0)
  await expect(page.locator('aside[aria-label="Project navigation"]').getByText(/Music\s*1/)).toBeVisible()
  await page.getByRole('button', { name: 'Export' }).click()
  await expect(page.getByRole('dialog')).toHaveAccessibleName('Export is planned')
  await expect(page.getByText('This preview does not run AI analysis, process media, or generate videos.')).toBeVisible()
})
