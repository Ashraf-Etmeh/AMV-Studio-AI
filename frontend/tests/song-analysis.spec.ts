import { expect, test } from '@playwright/test'
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'

test('sample sections, views, and marker controls stay visibly labeled', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Projects', exact: true }).click()
  await page.getByRole('button', { name: 'Open project Beneath the Sky' }).click()
  await page.getByRole('button', { name: 'Song Analysis' }).click()
  await expect(page.getByRole('heading', { name: 'Beneath the Sky' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Demo analysis' })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByText('Demo values are illustrative and unrelated to imported files.')).toBeVisible()
  await expect(page.getByText('Selected: Chorus')).toBeVisible()
  await page.locator('section[aria-label="Sample analysis details"]').getByRole('button', { name: /Even if we’re drifting/ }).click()
  await expect(page.getByText('Selected: Bridge')).toBeVisible()
  await expect(page.getByText('2:10 – 2:39 · Reflective · energy 0.64')).toBeVisible()
  await page.getByRole('tab', { name: 'Structure' }).click()
  await expect(page.getByRole('heading', { name: 'Sample song structure' })).toBeVisible()
  await page.getByRole('tab', { name: 'Beats' }).click()
  await expect(page.getByRole('heading', { name: 'Illustrative beat markers' })).toBeVisible()
  await page.getByRole('checkbox', { name: 'Show demo markers' }).uncheck()
  await expect(page.getByText(/Markers are hidden/)).toBeVisible()
  await page.getByRole('tab', { name: 'Emotion Curve' }).click()
  await expect(page.getByRole('img', { name: 'Illustrative sample energy curve' })).toBeVisible()
  await page.getByRole('tab', { name: 'Lyric Segments' }).click()
  await page.locator('section[aria-label="Sample analysis details"]').getByRole('button', { name: /So let me stay in this moment/ }).click()
  await expect(page.getByText('Selected: Chorus')).toBeVisible()
  await page.screenshot({ path: 'test-results/song-analysis-1672x941.png', fullPage: true })
  for (const viewport of [{ width: 1280, height: 800 }, { width: 390, height: 844 }]) {
    await page.setViewportSize(viewport)
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: `test-results/song-analysis-${viewport.width}x${viewport.height}.png`, fullPage: true })
  }
  expect(errors).toEqual([])
})

test('imported music has local playback without fabricated analysis', async ({ page }) => {
  const audioPath = path.resolve('test-results', 'song-analysis-second.wav')
  await mkdir(path.dirname(audioPath), { recursive: true })
  const sampleCount = 8_000
  const wav = Buffer.alloc(44 + sampleCount * 2)
  wav.write('RIFF', 0); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVE', 8)
  wav.write('fmt ', 12); wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20)
  wav.writeUInt16LE(1, 22); wav.writeUInt32LE(8_000, 24); wav.writeUInt32LE(16_000, 28)
  wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34)
  wav.write('data', 36); wav.writeUInt32LE(sampleCount * 2, 40)
  await writeFile(audioPath, wav)
  await page.goto('/')
  await page.getByRole('button', { name: 'Projects', exact: true }).click()
  await page.getByRole('button', { name: 'New Project' }).click()
  await page.getByLabel('Project name').fill('My soundtrack')
  await page.getByRole('button', { name: 'Create Project' }).click()
  await page.getByLabel('Choose media files').setInputFiles(audioPath)
  await page.getByRole('button', { name: 'Song Analysis' }).click()
  await page.getByRole('button', { name: 'Your music (1)' }).click()
  await expect(page.locator('audio[aria-label="Play song-analysis-second.wav"]')).toBeVisible()
  await expect(page.getByText('No BPM, lyrics, emotion, waveform, or sections have been inferred from your file.')).toBeVisible()
  await expect(page.getByText('Song Intelligence')).toHaveCount(0)
  await page.reload()
  await page.getByRole('button', { name: 'Your music (1)' }).click()
  await expect(page.locator('audio[aria-label="Play song-analysis-second.wav"]')).toHaveAttribute('src', /^blob:/)
  await expect(page.getByText('No BPM, lyrics, emotion, waveform, or sections have been inferred from your file.')).toBeVisible()
})
