import { expect, test } from '@playwright/test'
import { writeFile, mkdir } from 'node:fs/promises'
import path from 'node:path'

const testFile = path.resolve('src', 'assets', 'demo', 'project-sky.png')
const mismatchFile = path.resolve('test-results', 'different-image.png')

test('imports a local image, preserves metadata, and relinks its preview after reload', async ({ page }) => {
  await mkdir(path.dirname(testFile), { recursive: true })
  await writeFile(mismatchFile, Buffer.from('different'))
  await page.goto('/')
  await page.getByRole('button', { name: 'Projects', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Projects' })).toBeVisible()
  await page.screenshot({ path: 'test-results/projects-page.png', fullPage: true })
  await page.getByRole('button', { name: 'New Project' }).click()
  await page.getByLabel('Project name').fill('Neon Memory')
  await page.getByRole('button', { name: 'Create Project' }).click()
  await expect(page.getByRole('heading', { name: 'Neon Memory' })).toBeVisible()
  await page.getByLabel('Choose media files').setInputFiles(testFile)
  await expect(page.getByRole('button', { name: /project-sky.png/ })).toBeVisible()
  await expect(page.getByText('318 × 82')).toBeVisible()
  await expect(page.getByText('Ready in this session')).toBeVisible()
  await expect(page.getByAltText('Preview of project-sky.png')).toBeVisible()
  for (const viewport of [{ width: 1280, height: 800 }, { width: 390, height: 844 }]) {
    await page.setViewportSize(viewport)
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  }
  await page.setViewportSize({ width: 1672, height: 941 })
  await page.screenshot({ path: 'test-results/media-workspace.png', fullPage: true })
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Neon Memory' })).toBeVisible()
  await expect(page.getByText('Relink required', { exact: true })).toBeVisible()
  await expect(page.getByText('318 × 82')).toBeVisible()
  await page.getByRole('button', { name: 'Relink file' }).click()
  await page.getByLabel('Choose original file to relink').setInputFiles(mismatchFile)
  await expect(page.getByRole('alert')).toContainText('same name, size, and modified date')
  await page.getByRole('button', { name: 'Relink file' }).click()
  await page.getByLabel('Choose original file to relink').setInputFiles(testFile)
  await expect(page.getByText('Ready in this session')).toBeVisible()
  await expect(page.getByAltText('Preview of project-sky.png')).toBeVisible()
  await page.getByRole('button', { name: 'Remove record' }).click()
  await expect(page.getByRole('dialog')).toContainText('original file stays on your computer')
  await page.getByRole('dialog').getByRole('button', { name: 'Remove record' }).click()
  await expect(page.getByText('Your media library is ready')).toBeVisible()
})

test('reads duration from a selected local audio file', async ({ page }) => {
  await mkdir(path.dirname(mismatchFile), { recursive: true })
  const audioPath = path.resolve('test-results', 'one-second.wav')
  const samples = 8_000
  const wav = Buffer.alloc(44 + samples * 2)
  wav.write('RIFF', 0); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVE', 8)
  wav.write('fmt ', 12); wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20)
  wav.writeUInt16LE(1, 22); wav.writeUInt32LE(8_000, 24); wav.writeUInt32LE(16_000, 28)
  wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34)
  wav.write('data', 36); wav.writeUInt32LE(samples * 2, 40)
  await writeFile(audioPath, wav)
  await page.goto('/')
  await page.getByRole('button', { name: 'Projects', exact: true }).click()
  await page.getByRole('button', { name: 'Open project Beneath the Sky' }).click()
  await page.getByLabel('Choose media files').setInputFiles(audioPath)
  await expect(page.getByRole('button', { name: /one-second.wav/ })).toBeVisible()
  await expect(page.locator('audio[aria-label="Preview of one-second.wav"]')).toBeVisible()
  await expect(page.getByText('00:01')).toBeVisible()
  await expect(page.getByText('1 music')).toBeVisible()
})

test('deleting a local project removes its browser record while samples remain', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Projects', exact: true }).click()
  await page.getByRole('button', { name: 'New Project' }).click()
  await page.getByLabel('Project name').fill('Temporary edit')
  await page.getByRole('button', { name: 'Create Project' }).click()
  await page.locator('#workspace-main').getByRole('button', { name: 'Projects' }).click()
  await expect(page.getByRole('button', { name: 'Delete Temporary edit' })).toBeVisible()
  await page.getByRole('button', { name: 'Delete Temporary edit' }).click()
  await expect(page.getByRole('dialog')).toContainText('original files stay on your computer')
  await page.getByRole('dialog').getByRole('button', { name: 'Delete project' }).click()
  await expect(page.getByRole('button', { name: 'Open project Temporary edit' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Open project Beneath the Sky' })).toBeVisible()
})
